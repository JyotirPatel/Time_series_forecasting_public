def run_fold(
    train_frame: pd.DataFrame,
    valid_frame: pd.DataFrame,
    *,
    mode: str,
    residual_horizons: list[int],
    incumbent_config: dict[str, object] | None,
    lgbm_params: dict[str, object],
    lgbm_fit_kwargs: dict[str, int],
    use_sample_weight: bool,
    apply_residual_only_warm: bool,
    residual_warm_only_horizons: list[int] | None,
    precomputed_train_oof: pd.Series | None = None,
    prepared_train_features: PreparedFeatureFrame | None = None,
) -> pd.DataFrame:
    """Train and evaluate one fold.  Returns scored DataFrame with prediction."""
    extra_cols: list[str] = []
    effective_warm_only_horizons = normalize_residual_warm_only_horizons(
        residual_warm_only_horizons,
        residual_horizons=residual_horizons,
        apply_residual_only_warm=apply_residual_only_warm,
    )
    train_seen_pairs = (
        build_seen_sub_code_pairs(train_frame)
        if mode == "residual" and effective_warm_only_horizons
        else None
    )

    if mode in ("stacked", "residual") and incumbent_config is not None:
        # Strict OOF incumbent predictions for training data
        if precomputed_train_oof is not None:
            print("    Using precomputed OOF incumbent predictions for train...")
            train_oof = precomputed_train_oof.loc[train_frame.index]
        else:
            print("    Building OOF incumbent predictions for train...")
            oof_t0 = time.perf_counter()
            train_oof = build_oof_incumbent_predictions(
                train_frame, incumbent_config,
            )
            print(
                f"    OOF done ({time.perf_counter() - oof_t0:.1f}s), "
                f"coverage: {int(train_oof.notna().sum()):,}/{len(train_oof):,}"
            )
        oof_coverage = int(train_oof.notna().sum())
        if precomputed_train_oof is not None:
            print(
                f"    OOF coverage: {oof_coverage:,}/{len(train_oof):,}"
            )

        valid_oof = (
            precomputed_train_oof.reindex(valid_frame.index)
            if precomputed_train_oof is not None
            else None
        )
        if valid_oof is not None and valid_oof.notna().all():
            print("    Using precomputed OOF incumbent predictions for validation...")
            valid_inc = valid_oof.to_numpy(dtype=float)
        else:
            # Direct incumbent prediction on validation is still leakage-safe
            # when the global OOF series does not cover these rows.
            valid_inc = _fit_predict_incumbent(
                train_frame, valid_frame, incumbent_config,
            )

        if oof_coverage == 0:
            # Fallback: in-fold incumbent predictions (group-level leakage
            # only — incumbent is smoothed group means + overlays, not
            # row-level).  Log the caveat.
            print("    WARNING: No OOF coverage — using in-fold incumbent "
                  "predictions (group-level leakage)")
            train_inc = _fit_predict_incumbent(
                train_frame, train_frame, incumbent_config,
            )
            train_frame = train_frame.copy()
            train_frame["incumbent_pred"] = train_inc
        else:
            has_oof = train_oof.notna()
            train_frame = train_frame.loc[has_oof].copy()
            train_frame["incumbent_pred"] = train_oof.loc[has_oof].values

        valid_frame = valid_frame.copy()
        valid_frame["incumbent_pred"] = valid_inc

        extra_cols.append("incumbent_pred")
        print(f"    Train rows with incumbent_pred: {len(train_frame):,}")

    transformer = build_transformer(incumbent_config or {})
    has_custom_transformer = bool((incumbent_config or {}).get("transformer") is not None)
    if has_custom_transformer:
        transformed_train = transformer.fit(train_frame).transform_batch(train_frame)
        transformed_valid = transformer.transform_batch(valid_frame)
        train_frame = transformed_train
        valid_frame = transformed_valid
        prepared_train_features = None

    train_feature_frame: pd.DataFrame | None = None
    valid_feature_frame: pd.DataFrame | None = None
    if prepared_train_features is not None:
        train_feature_frame, valid_feature_frame = materialize_prepared_fold_features(
            prepared_train_features,
            train_index=train_frame.index,
            valid_index=valid_frame.index,
        )

    if mode == "residual" and "incumbent_pred" in train_frame.columns:
        # Residual target: only for gated horizons
        residual_mask_train = train_frame[HORIZON_COLUMN].isin(residual_horizons)
        residual_mask_valid = build_residual_prediction_mask(
            valid_frame,
            residual_horizons=residual_horizons,
            apply_residual_only_warm=apply_residual_only_warm,
            seen_pairs=train_seen_pairs,
            residual_warm_only_horizons=effective_warm_only_horizons,
        )

        # Train LightGBM only on residual-eligible rows
        lgbm_train = train_frame.loc[residual_mask_train].copy()
        lgbm_train[TARGET_COLUMN] = (
            lgbm_train[TARGET_COLUMN] - lgbm_train["incumbent_pred"]
        )

        lgbm_valid = valid_frame.loc[residual_mask_valid].copy()
        all_preds = valid_frame["incumbent_pred"].copy()
        if len(lgbm_valid) > 0:
            lgbm_valid[TARGET_COLUMN] = (
                lgbm_valid[TARGET_COLUMN] - lgbm_valid["incumbent_pred"]
            )

            prepared_lgbm_train = (
                train_feature_frame.loc[residual_mask_train].copy()
                if train_feature_frame is not None
                else None
            )
            prepared_lgbm_valid = (
                valid_feature_frame.loc[residual_mask_valid].copy()
                if valid_feature_frame is not None
                else None
            )
            if prepared_lgbm_train is not None:
                prepared_lgbm_train["incumbent_pred"] = (
                    lgbm_train["incumbent_pred"].to_numpy(dtype=float)
                )
            if prepared_lgbm_valid is not None:
                prepared_lgbm_valid["incumbent_pred"] = (
                    lgbm_valid["incumbent_pred"].to_numpy(dtype=float)
                )

            model = LGBMForecaster(
                params=lgbm_params,
                extra_numeric_columns=extra_cols or None,
                use_sample_weight=use_sample_weight,
                **lgbm_fit_kwargs,
            )
            fit_kwargs: dict[str, object] = {"eval_frame": lgbm_valid}
            if prepared_lgbm_train is not None:
                fit_kwargs["prepared_train_frame"] = prepared_lgbm_train
            if prepared_lgbm_valid is not None:
                fit_kwargs["prepared_eval_frame"] = prepared_lgbm_valid
            model.fit(lgbm_train, **fit_kwargs)

            # Predictions: residual correction on gated rows, incumbent on rest
            predict_kwargs: dict[str, object] = {}
            if prepared_lgbm_valid is not None:
                predict_kwargs["prepared_frame"] = prepared_lgbm_valid
            residual_preds = model.predict(
                valid_frame.loc[residual_mask_valid],
                **predict_kwargs,
            )
            all_preds.loc[residual_mask_valid] = (
                valid_frame.loc[residual_mask_valid, "incumbent_pred"] + residual_preds
            )
        predictions = all_preds.values
    else:
        prepared_train_for_model = (
            train_feature_frame.copy() if train_feature_frame is not None else None
        )
        prepared_valid_for_model = (
            valid_feature_frame.copy() if valid_feature_frame is not None else None
        )
        if prepared_train_for_model is not None and "incumbent_pred" in train_frame.columns:
            prepared_train_for_model["incumbent_pred"] = (
                train_frame["incumbent_pred"].to_numpy(dtype=float)
            )
        if prepared_valid_for_model is not None and "incumbent_pred" in valid_frame.columns:
            prepared_valid_for_model["incumbent_pred"] = (
                valid_frame["incumbent_pred"].to_numpy(dtype=float)
            )

        model = LGBMForecaster(
            params=lgbm_params,
            extra_numeric_columns=extra_cols or None,
            use_sample_weight=use_sample_weight,
            **lgbm_fit_kwargs,
        )
        fit_kwargs = {"eval_frame": valid_frame}
        if prepared_train_for_model is not None:
            fit_kwargs["prepared_train_frame"] = prepared_train_for_model
        if prepared_valid_for_model is not None:
            fit_kwargs["prepared_eval_frame"] = prepared_valid_for_model
        model.fit(train_frame, **fit_kwargs)
        predict_kwargs = {}
        if prepared_valid_for_model is not None:
            predict_kwargs["prepared_frame"] = prepared_valid_for_model
        predictions = model.predict(valid_frame, **predict_kwargs)

    scored = valid_frame[
        [ID_COLUMN, CODE_COLUMN, SUB_CODE_COLUMN, SUB_CATEGORY_COLUMN,
         HORIZON_COLUMN, TARGET_COLUMN, WEIGHT_COLUMN]
    ].copy()
    scored["prediction"] = predictions
    return scored


def write_scored_fold_frame(
    scored: pd.DataFrame,
    *,
    output_dir: Path,
    model_name: str,
    fold_name: str,
) -> Path:
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    output_path = output_dir / f"{model_name}_{fold_name}_scored.parquet"
    scored.to_parquet(output_path, index=False)
    return output_path


