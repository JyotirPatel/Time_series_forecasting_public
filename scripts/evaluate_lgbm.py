def normalize_residual_horizons(
    residual_horizons: list[int] | None,
) -> list[int]:
    if residual_horizons is None:
        return list(DEFAULT_RESIDUAL_HORIZONS)
    return sorted({int(horizon) for horizon in residual_horizons})


def normalize_residual_warm_only_horizons(
    residual_warm_only_horizons: list[int] | None,
    *,
    residual_horizons: list[int],
    apply_residual_only_warm: bool,
) -> list[int]:
    if residual_warm_only_horizons is None:
        return list(residual_horizons) if apply_residual_only_warm else []
    residual_horizon_set = set(residual_horizons)
    return [
        int(horizon)
        for horizon in sorted({int(horizon) for horizon in residual_warm_only_horizons})
        if int(horizon) in residual_horizon_set
    ]


def build_residual_prediction_mask(
    frame: pd.DataFrame,
    *,
    residual_horizons: list[int],
    apply_residual_only_warm: bool,
    seen_pairs: set[tuple[str, str]] | None,
    residual_warm_only_horizons: list[int] | None = None,
) -> pd.Series:
    mask = frame[HORIZON_COLUMN].isin(residual_horizons)
    warm_only_horizons = normalize_residual_warm_only_horizons(
        residual_warm_only_horizons,
        residual_horizons=residual_horizons,
        apply_residual_only_warm=apply_residual_only_warm,
    )
    if not warm_only_horizons:
        return mask
    if seen_pairs is None:
        raise ValueError("seen_pairs are required when warm-only gating is enabled")

    warm_mask = pd.Series(
        list(zip(frame[CODE_COLUMN], frame[SUB_CODE_COLUMN], strict=True)),
        index=frame.index,
    ).isin(seen_pairs)
    warm_only_mask = frame[HORIZON_COLUMN].isin(warm_only_horizons)
    return mask & (~warm_only_mask | warm_mask)


def load_fold_frames(
    train_path: str,
    fold: ExpandingWindowFold,
    *,
    load_cols: list[str],
    preloaded_train_frame: pd.DataFrame | None = None,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Load or slice the train / validation frames for one outer fold."""

    if preloaded_train_frame is not None:
        ts = preloaded_train_frame[TIME_COLUMN]
        train_frame = preloaded_train_frame.loc[
            ts <= fold.train_end_ts, load_cols
        ].copy()
        valid_frame = preloaded_train_frame.loc[
            (ts > fold.train_end_ts) & (ts <= fold.validation_end_ts), load_cols
        ].copy()
        return train_frame, valid_frame

    train_frame = read_parquet_frame(
        train_path,
        columns=load_cols,
        where=f"{TIME_COLUMN} <= {fold.train_end_ts}",
    )
    valid_frame = read_parquet_frame(
        train_path,
        columns=load_cols,
        where=(
            f"{TIME_COLUMN} > {fold.train_end_ts} AND "
            f"{TIME_COLUMN} <= {fold.validation_end_ts}"
        ),
    )
    return train_frame, valid_frame


def materialize_prepared_fold_features(
    prepared_features: PreparedFeatureFrame,
    *,
    train_index: pd.Index,
    valid_index: pd.Index,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Slice prebuilt base features once and materialize fold-specific dtypes."""
    train_prepared = prepared_features.slice_rows(train_index)
    train_features, _, train_category_maps = train_prepared.to_frame()
    valid_prepared = prepared_features.slice_rows(valid_index)
    valid_features, _, _ = valid_prepared.to_frame(category_maps=train_category_maps)
    return train_features, valid_features


