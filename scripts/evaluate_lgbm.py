def _fit_predict_incumbent(
    train_frame: pd.DataFrame,
    predict_frame: pd.DataFrame,
    config: dict[str, object],
) -> np.ndarray:
    """Fit incumbent on *train_frame*, return predictions on *predict_frame*."""
    pipeline = SequentialInferencePipeline(
        transformer=IdentityTransformer(),
        predictor=build_predictor(config),
    ).fit(train_frame)
    preds_df = pipeline.predict(predict_frame)
    merged = predict_frame[[ID_COLUMN]].merge(
        preds_df[[ID_COLUMN, "prediction"]], on=ID_COLUMN, how="left",
    )
    return merged["prediction"].to_numpy(dtype=float)


def build_oof_incumbent_predictions(
    train_frame: pd.DataFrame,
    config: dict[str, object],
    *,
    oof_holdout_steps: int = 360,
    oof_step_size: int = 360,
    oof_min_train_steps: int = 1000,
) -> pd.Series:
    """Build strict out-of-fold incumbent predictions for training data.

    Uses expanding-window sub-folds within *train_frame* so that each
    row's incumbent prediction was generated by a model that never saw
    that row's target.  Rows not covered by any sub-fold holdout are NaN
    and should be excluded from LightGBM training.
    """
    max_ts = int(train_frame[TIME_COLUMN].max())
    # Maximise sub-folds: compute how many fit
    available = max_ts - oof_holdout_steps - oof_min_train_steps
    max_n_folds = max(1, available // oof_step_size + 1) if available >= 0 else 0
    if max_n_folds == 0:
        return pd.Series(np.nan, index=train_frame.index, dtype=float)
    try:
        sub_folds = build_expanding_window_folds(
            max_ts_index=max_ts,
            holdout_steps=oof_holdout_steps,
            n_folds=max_n_folds,
            step_size=oof_step_size,
            min_train_steps=oof_min_train_steps,
        )
    except ValueError:
        return pd.Series(np.nan, index=train_frame.index, dtype=float)

    oof_preds = pd.Series(np.nan, index=train_frame.index, dtype=float)
    ts = train_frame[TIME_COLUMN]

    for sub_fold in sub_folds:
        sub_train = train_frame[ts <= sub_fold.train_end_ts]
        sub_valid_mask = (
            (ts > sub_fold.train_end_ts)
            & (ts <= sub_fold.validation_end_ts)
        )
        sub_valid = train_frame[sub_valid_mask]
        if len(sub_valid) == 0:
            continue

        preds = _fit_predict_incumbent(sub_train, sub_valid, config)
        oof_preds.loc[sub_valid_mask] = preds

    return oof_preds


def build_precomputed_oof_cache_path(
    cache_dir: str | Path,
    *,
    incumbent_name: str,
    train_path: str,
    oof_holdout_steps: int = 360,
    oof_step_size: int = 360,
    oof_min_train_steps: int = 1000,
) -> Path:
    cache_root = Path(cache_dir)
    cache_root.mkdir(parents=True, exist_ok=True)
    train_stem = Path(train_path).stem
    cache_name = (
        f"{train_stem}_{incumbent_name}"
        f"_h{oof_holdout_steps}_s{oof_step_size}_m{oof_min_train_steps}.parquet"
    )
    return cache_root / cache_name


def write_precomputed_oof_cache(cache_path: str | Path, oof_series: pd.Series) -> None:
    cache_frame = pd.DataFrame(
        {
            "row_index": oof_series.index.to_numpy(),
            "prediction": oof_series.to_numpy(dtype=float),
        }
    )
    Path(cache_path).parent.mkdir(parents=True, exist_ok=True)
    cache_frame.to_parquet(cache_path, index=False)


def load_precomputed_oof_cache(cache_path: str | Path) -> pd.Series:
    cache_frame = pd.read_parquet(cache_path)
    return pd.Series(
        cache_frame["prediction"].to_numpy(dtype=float),
        index=cache_frame["row_index"].to_numpy(),
        dtype=float,
    )


def resolve_precomputed_train_oof(
    *,
    cache_dir: str | Path,
    train_path: str,
    incumbent_name: str,
    train_frame: pd.DataFrame,
    incumbent_config: dict[str, object],
    oof_holdout_steps: int = 360,
    oof_step_size: int = 360,
    oof_min_train_steps: int = 1000,
) -> pd.Series:
    cache_path = build_precomputed_oof_cache_path(
        cache_dir,
        incumbent_name=incumbent_name,
        train_path=train_path,
        oof_holdout_steps=oof_holdout_steps,
        oof_step_size=oof_step_size,
        oof_min_train_steps=oof_min_train_steps,
    )
    if cache_path.exists():
        print(f"Loading cached incumbent OOF predictions from {cache_path}...")
        return load_precomputed_oof_cache(cache_path)

    print(f"Precomputing full-train incumbent OOF predictions into {cache_path}...")
    oof_series = build_oof_incumbent_predictions(
        train_frame,
        incumbent_config,
        oof_holdout_steps=oof_holdout_steps,
        oof_step_size=oof_step_size,
        oof_min_train_steps=oof_min_train_steps,
    )
    write_precomputed_oof_cache(cache_path, oof_series)
    return oof_series


def build_lgbm_params(args: argparse.Namespace) -> dict[str, object]:
    params = dict(DEFAULT_PARAMS)
    override_names = (
        "num_leaves",
        "max_depth",
        "learning_rate",
        "min_child_samples",
        "min_sum_hessian_in_leaf",
        "feature_fraction",
        "bagging_fraction",
        "bagging_freq",
        "min_split_gain",
        "reg_alpha",
        "reg_lambda",
        "num_threads",
        "device_type",
        "seed",
    )
    for name in override_names:
        value = getattr(args, name, None)
        if value is not None:
            params[name] = value
    return params


